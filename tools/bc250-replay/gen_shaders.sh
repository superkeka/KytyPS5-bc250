#!/bin/sh
# Regenerates readback_shaders.h from readback.s (gfx1013, wave64). Needs llvm-mc and llvm-objcopy.
set -e
cd "$(dirname "$0")"
LLVM_BIN=${LLVM_BIN:-/opt/homebrew/opt/llvm/bin}
TMP=$(mktemp -d)
OUT=readback_shaders.h
echo "// Generated by gen_shaders.sh from readback.s (gfx1013, wave64). Do not edit." > "$OUT"
echo "#pragma once" >> "$OUT"
echo "#include <cstdint>" >> "$OUT"
for v in "2d|v[12:13]|SQ_RSRC_IMG_2D" "2d_array|v[12:14]|SQ_RSRC_IMG_2D_ARRAY" "3d|v[12:14]|SQ_RSRC_IMG_3D"; do
	name=${v%%|*}; rest=${v#*|}; addr=${rest%%|*}; dim=${rest#*|}
	sed "s/IMAGE_LOAD/image_load v[8:11], $addr, s[0:7] dmask:0xf dim:$dim/" readback.s > "$TMP/$name.s"
	"$LLVM_BIN/llvm-mc" -triple=amdgcn -mcpu=gfx1013 -mattr=+wavefrontsize64 -filetype=obj "$TMP/$name.s" -o "$TMP/$name.o"
	"$LLVM_BIN/llvm-objcopy" -O binary --only-section=.text "$TMP/$name.o" "$TMP/$name.bin"
	echo "static const uint8_t kReadback_$name[] = {" >> "$OUT"
	od -An -v -tx1 "$TMP/$name.bin" | sed 's/  */ /g;s/^ //;s/ $//;s/\([0-9a-f][0-9a-f]\)/0x\1,/g;s/^/\t/' >> "$OUT"
	echo "};" >> "$OUT"
done
rm -rf "$TMP"
