#!/bin/sh
# Regenerates shaders.h from the .s sources. Needs llvm-mc and llvm-objcopy (LLVM 17+).
set -e
LLVM_BIN=${LLVM_BIN:-/opt/homebrew/opt/llvm/bin}
TMP=$(mktemp -d)
OUT=shaders.h
echo "// Generated by gen_shaders.sh from *.s (gfx1013; dot2c.s as gfx1030). Do not edit." > "$OUT"
echo "#pragma once" >> "$OUT"
echo "#include <stdint.h>" >> "$OUT"
for src in store stream poll poll_cached long dot2c gds dot2x dot2emu; do
	cpu=gfx1013
	[ "$src" = dot2c ] && cpu=gfx1030
	for w in 32 64; do
		"$LLVM_BIN/llvm-mc" -triple=amdgcn -mcpu=$cpu -mattr=+wavefrontsize$w -filetype=obj "$src.s" -o "$TMP/$src$w.o"
		"$LLVM_BIN/llvm-objcopy" -O binary --only-section=.text "$TMP/$src$w.o" "$TMP/$src$w.bin"
		echo "static const uint8_t k_${src}_w$w[] = {" >> "$OUT"
		od -An -v -tx1 "$TMP/$src$w.bin" | sed 's/  */ /g;s/^ //;s/ $//;s/\([0-9a-f][0-9a-f]\)/0x\1,/g;s/^/\t/' >> "$OUT"
		echo "};" >> "$OUT"
	done
done
rm -rf "$TMP"
